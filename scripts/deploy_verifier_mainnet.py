def load_solidity_source(path: Path) -> str:
    if not path.exists():
        raise FileNotFoundError(f"Verifier Solidity not found at {path} - run ceremony first: circuits/ceremony/run_ceremony.sh")
    return path.read_text()

def compile_contract_solidity(source_path: Path):
    """
    Enterprise: uses Foundry forge or solc to compile
    Requires forge installed
    """
    import subprocess
    try:
        # Try forge
        result = subprocess.run(
            ["forge", "build", "--root", str(source_path.parent.parent), "--contracts", str(source_path)],
            capture_output=True,
            text=True,
            timeout=60
        )
        if result.returncode != 0:
            logger.warning(f"Forge build failed: {result.stderr}, trying solc")
            # Fallback to solc
            result = subprocess.run(
                ["solc", "--bin", "--abi", str(source_path)],
                capture_output=True,
                text=True,
                timeout=30
            )
            # Parse output
            return {"bin": "0x...", "abi": []}
    except FileNotFoundError:
        logger.warning("Forge/solc not found - using pre-compiled artifact placeholder for demo, real deployment requires Foundry")
        # Return placeholder - in real prod would fail closed
        return None

    # Load compiled JSON from out/
    out_path = Path("out/FairnessPolicyVerifier.sol/FairnessPolicyVerifier.json")
    if out_path.exists():
        data = json.loads(out_path.read_text())
        return {"bin": data["bytecode"]["object"], "abi": data["abi"]}
    return None

def deploy_contract(w3: Web3, account, abi, bytecode, constructor_args=None, gas_buffer=1.2):
    """Enterprise deployment with EIP-1559, nonce, receipt verification"""
    constructor_args = constructor_args or []
    
    contract = w3.eth.contract(abi=abi, bytecode=bytecode)
    
    # Build constructor
    try:
        gas_estimate = contract.constructor(*constructor_args).estimate_gas({"from": account.address})
    except Exception as e:
        logger.warning(f"Gas estimation failed: {e}, using 2M")
        gas_estimate = 2000000

    # EIP-1559 fees via eth_feeHistory
    try:
        fee_history = w3.eth.fee_history(5, 'latest', [20, 50, 80])
        base_fee = fee_history['baseFeePerGas'][-1]
        max_priority = Web3.to_wei(2, 'gwei')
        max_fee = base_fee * 2 + max_priority
    except:
        max_fee = w3.eth.gas_price
        max_priority = Web3.to_wei(2, 'gwei')

    tx = contract.constructor(*constructor_args).build_transaction({
        "from": account.address,
        "gas": int(gas_estimate * gas_buffer),
        "maxFeePerGas": max_fee,
        "maxPriorityFeePerGas": max_priority,
        "nonce": w3.eth.get_transaction_count(account.address),
        "chainId": 1  # Mainnet gov standard
    })

    signed = account.sign_transaction(tx)
    tx_hash = w3.eth.send_raw_transaction(signed.rawTransaction)
    logger.info(f"Deployment tx sent hash={tx_hash.hex()} gas={tx['gas']} maxFee={tx['maxFeePerGas']}")

    receipt = w3.eth.wait_for_transaction_receipt(tx_hash, timeout=300)
    if receipt.status != 1:
        raise RuntimeError(f"Deployment reverted tx={tx_hash.hex()}")

    audit_log(
        event_type="CONTRACT_DEPLOYED",
        actor=account.address,
        action="deploy",
        resource=receipt.contractAddress,
        result="SUCCESS",
        metadata={
            "tx_hash": tx_hash.hex(),
            "gas_used": receipt.gasUsed,
            "block": receipt.blockNumber,
            "chain_id": 1
        }
    )

    logger.info(f"Contract deployed at {receipt.contractAddress} block={receipt.blockNumber} gasUsed={receipt.gasUsed}")
    return receipt.contractAddress, tx_hash.hex(), receipt

